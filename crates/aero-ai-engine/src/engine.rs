use aero_config::AiConfig;
use aero_protocol::AeroResult;
use parking_lot::RwLock;

pub struct AiEngine {
    config: AiConfig,
    loaded: RwLock<bool>,
}

impl AiEngine {
    pub async fn new(config: AiConfig) -> anyhow::Result<Self> {
        tracing::info!(
            model = %config.model_name,
            quantization = %config.quantization,
            gpu = ?config.gpu_backend,
            "Initializing embedded AI engine"
        );

        let engine = Self {
            config,
            loaded: RwLock::new(false),
        };

        engine.load_model().await?;

        Ok(engine)
    }

    async fn load_model(&self) -> anyhow::Result<()> {
        tracing::info!("Loading SLM model into memory (stub — wire Candle/mistral.rs here)");

        *self.loaded.write() = true;

        tracing::info!("Model loaded, AI engine ready for local inference");
        Ok(())
    }

    pub async fn generate_text(&self, prompt: &str) -> AeroResult<String> {
        if !*self.loaded.read() {
            return Err(aero_protocol::AeroError::AiEngine(
                "Model not loaded".into(),
            ));
        }

        tracing::debug!(prompt_len = prompt.len(), "Generating text via local SLM");

        Ok(format!(
            "[AeroBaaS Local AI] Processed prompt ({} chars). Response generated by embedded {} model.",
            prompt.len(),
            self.config.model_name
        ))
    }

    pub async fn validate_content(&self, content: &str) -> AeroResult<ValidationResult> {
        let suspicious_patterns = ["ignore previous", "system prompt", "jailbreak", "override"];

        let is_suspicious = suspicious_patterns
            .iter()
            .any(|p| content.to_lowercase().contains(p));

        Ok(ValidationResult {
            is_safe: !is_suspicious,
            threat_type: if is_suspicious {
                Some(ThreatType::PromptInjection)
            } else {
                None
            },
            confidence: if is_suspicious { 0.85 } else { 0.95 },
        })
    }

    pub fn memory_usage_mb(&self) -> u32 {
        0
    }

    pub fn is_loaded(&self) -> bool {
        *self.loaded.read()
    }
}

#[derive(Debug, Clone, serde::Serialize)]
pub struct ValidationResult {
    pub is_safe: bool,
    pub threat_type: Option<ThreatType>,
    pub confidence: f64,
}

#[derive(Debug, Clone, serde::Serialize)]
#[serde(rename_all = "snake_case")]
pub enum ThreatType {
    PromptInjection,
    ToxicContent,
    SpamContent,
    CodeInjection,
    DataExfiltration,
}
